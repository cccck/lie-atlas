/** Build the precomputed loop model for the current state. */
export function buildModel(S) {
  const world = S.world;
  const eps = Math.max(1e-4, S.eps[world]);
  const alpha = (S.alpha * Math.PI) / 180;
  const params = { alpha, qB: S.qB, kappa: S.kappa, lat0: (S.lat0 * Math.PI) / 180, showA: S.showA };
  if (world === 'sphere') {
    const P = sphereLoop(params.lat0, eps);
    const B0 = sphereBasis(params.lat0, 0);
    const V0 = B0.east;
    const at = (s) => sphereAt(P, s);
    const samples = [0, 1, 2, 3].map((i) => Array.from({ length: N + 1 }, (_, j) => at(i + j / N)));
    const liftOf = (st) => {
      const [e, n] = sphereNormalCoords(B0, st.p);
      return [e / eps, n / eps, sphereRadialAngle(B0.p, V0, st) / (eps * eps)];
    };
    const hol = sphereHolonomy(P);
    return {
      world, eps, frame: 'body', params, P, at, samples,
      lift: samples.map((leg) => leg.map(liftOf)),
      liftAt: (s) => liftOf(at(s)),
      liftPred: [0, 0, 1],
      netCoords: [0, 0, hol],
      predCoords: [0, 0, eps * eps],
      net: samples[3][N],
      layoutKey: 'sphere',
    };
  }
  const W = world === 'rot' ? rotationWorld(alpha) : world === 'boost' ? boostWorld(alpha) : world === 'flux' ? fluxWorld(S.qB, alpha) : carWorld(S.kappa);
  const frame = S.frame;
  const nodes = loopNodes(W, eps, frame);
  const at = (s) => loopAt(W, eps, s, frame, nodes);
  const samples = [0, 1, 2, 3].map((i) => Array.from({ length: N + 1 }, (_, j) => at(i + j / N)));
  const liftOf = (g) => {
    const c = W.log(g);
    return [c[0] / eps, c[1] / eps, c[2] / (eps * eps)];
  };
  const predCoords = loopPrediction(W, eps, frame);
  return {
    world, eps, frame, params, W, nodes, at, samples,
    lift: samples.map((leg) => leg.map(liftOf)),
    liftAt: (s) => liftOf(at(s)),
    liftPred: [0, 0, predCoords[2] / (eps * eps)],
    netCoords: W.log(nodes[4]),
    predCoords,
    predNet: W.exp(predCoords),
    net: nodes[4],
    layoutKey: `${world}|${world === 'car' ? Math.sign(S.kappa) + ':' + Math.round(S.kappa * 4) : Math.round(S.alpha / 15)}`,
  };
}

/** |log g|, prediction and residual as functions of ε (for the log–log plot). */
function curveData(S, epsList) {
  const world = S.world;
  const out = { xs: epsList, net: [], pred: [], res: [] };
  if (world === 'sphere') {
    const lat0 = (S.lat0 * Math.PI) / 180;
    for (const e of epsList) {
      const h = sphereHolonomy(sphereLoop(lat0, e));
      out.net.push(Math.abs(h));
      out.pred.push(e * e);
      out.res.push(Math.abs(h - e * e));
    }
    return out;
  }
  const M0 = { ...S, eps: { ...S.eps } };
  for (const e of epsList) {
    M0.eps[world] = e;
    const W = buildWorld(M0);
    const net = W.log(loopNodes(W, e, S.frame)[4]);
    const pr = loopPrediction(W, e, S.frame);
    out.net.push(vnorm(net));
    out.pred.push(vnorm(pr));
    out.res.push(vnorm(vsub(net, pr)));
  }
  return out;
}
function buildWorld(S) {
  const a = (S.alpha * Math.PI) / 180;
  return S.world === 'rot' ? rotationWorld(a) : S.world === 'boost' ? boostWorld(a) : S.world === 'flux' ? fluxWorld(S.qB, a) : carWorld(S.kappa);
}

