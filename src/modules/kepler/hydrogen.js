// #/kepler, tab (c) — Hydrogen's n².
// Level diagram on an n* axis (columns l, 2l+1 dots per level) with a core-screening slider (quantum defects),
// and the (j, j) multiplet of SO(4) ≅ SU(2)×SU(2)/Z₂ morphing into the l-multiplets of SO(3).
import * as ui from '../../core/ui.js';
import { plot2d } from '../../core/plot2d.js';
import { fmt } from '../../core/format.js';
import { easeInOut } from '../../core/la.js';
import * as K from './math.js';

const NCOL = 5; // columns l = 0..4 in the level diagram
const NTOP = 5.55; // top of the n* axis
const NMAX_LEVELS = 9; // screened levels up to n = 9 can enter the window
const NGRID = 6; // largest shell in the multiplet view
const LCOL = ['c1', 'c2', 'c3', 'c4', 'c5', 'c6', 'c7', 'c8'];
const SY = 0.6; // vertical spacing of m in the (l, m) arrangement
const XL = -1.0; // left edge of the level diagram (room for the n labels)
const XR = NCOL + 1.4; // right edge (room for the energy labels)
/** Hydrogen level n in eV: E_n = −1/(2n²) Hartree. */
const eVof = (nstar) => -K.HARTREE_EV / (2 * nstar * nstar);

export function mountHydrogen(pg, scope, ctx) {
  const S = (ctx.state.hydrogen ??= { n: 3, screen: 0, u: 0, target: 0, auto: true });
  const col = ctx.colors;

  pg.stage.style.gridTemplateColumns = 'minmax(0, 1.3fr) minmax(0, 1fr)';
  scope.add(() => (pg.stage.style.gridTemplateColumns = ''));

  // ------------------------------------------------------------ views
  const vL = pg.view({ title: 'Levels of a one-electron atom', hint: 'click a level to pick its shell · vertical axis $n^*$' });
  const vG = pg.view({ title: 'The shell as an $SO(4)$ multiplet', hint: '' });
  vL.el.classList.add('kp-h-view');
  vG.el.classList.add('kp-h-view');
  const caption = vG.overlay('bl', 'overlay-card kp-caption');

  const pL = plot2d(vL.body, scope, {
    x: [XL, XR],
    y: [0.4, NTOP + 1.0],
    equal: false,
    pan: false,
    zoom: false,
    grid: false,
    axes: false,
    draw: drawLevels,
  });
  pL.on('click', (pos) => {
    let best = null;
    for (const b of bars()) {
      if (b.alpha < 0.3) continue;
      const dx = pL.sx(b.l) - pos.px;
      const dy = pL.sy(b.y) - pos.py;
      const d = Math.hypot(dx * 0.35, dy);
      if (!best || d < best.d) best = { d, n: b.n };
    }
    if (best && best.d < 40) sN.set(Math.min(NGRID, best.n));
  });

  const pG = plot2d(vG.body, scope, { x: [-3.2, 3.2], y: [-3.2, 3.2], pan: false, zoom: false, grid: false, axes: false, draw: drawGrid });

  // ------------------------------------------------------------ panel
  const secS = pg.section('Shell');
  const sN = ui.slider(secS, {
    label: 'Principal quantum number $n$',
    min: 1,
    max: NGRID,
    step: 1,
    value: S.n,
    format: (x) => `${x}  (${x * x} states)`,
    onInput: (x) => {
      S.n = Math.round(x);
      update();
    },
  });
  const seg = ui.segmented(secS, {
    label: 'Group the states by',
    options: [
      { value: 0, label: '$SU(2)\\times SU(2)$: $(m_1,m_2)$' },
      { value: 1, label: '$SO(3)$: $(l,m)$' },
    ],
    value: S.target,
    onChange: (v) => {
      S.target = v;
      S.auto = false;
      play.set(false, { silent: true });
    },
  });
  const play = ui.playButton(null, { playing: S.auto, labels: ['▶ Animate', '❚❚ Hold'], onToggle: (v) => (S.auto = v) });
  ui.buttons(secS, []).appendChild(play.el);

  const secB = pg.section('Break the hidden symmetry');
  const sScr = ui.slider(secB, {
    label: 'Core screening: hydrogen → sodium',
    min: 0,
    max: 1,
    step: 0.01,
    value: S.screen,
    format: (x) => fmt(x, 2),
    onInput: (x) => {
      S.screen = x;
      update();
    },
    help: 'Quantum defects $\\delta_s=1.35$, $\\delta_p=0.86$, $\\delta_d=0.01$, $\\delta_{l\\ge3}\\approx0$: $E_{nl}=-\\tfrac12(n-\\delta_l)^{-2}$ for $n\\ge3$.',
  });

  const secR = pg.section('Readout');
  const kv = ui.keyValue(secR, [
    ['Hydrogen $E_n=-1/2n^2$', ''],
    ['$j=(n-1)/2$', ''],
    ['Degeneracy $(2j+1)^2$', ''],
  ]);
  const ro = ui.readout(secR, { label: 'Branching $SO(4)\\to SO(3)$' });
  const roNa = ui.readout(secR, { label: 'Screened levels of this shell (eV)' });
  ui.legend(
    secR,
    [0, 1, 2, 3, 4].map((l) => ({ color: LCOL[l], label: `$l=${l}$ (${K.SPECTRO[l]})`, dot: true })),
  );

  ui.experiments(pg.section('Try this'), [
    {
      title: '$n^2$ states at one energy',
      text: 'Hydrogen, $n=3$: $1+3+5=9$ states share $E_3=-1.51$ eV. Rotations explain the $2l+1$ dots on each bar, not why the $s$, $p$ and $d$ bars sit at the same height — that is the hidden $SO(4)$.',
      apply: () => {
        sScr.set(0);
        sN.set(3);
        seg.set(0);
      },
    },
    {
      title: 'Regroup the multiplet',
      text: 'The shell is one $(j,j)$ multiplet, an $n\\times n$ grid of $(m_1,m_2)$. Ordinary rotations are generated by $\\vec L=\\vec J_1+\\vec J_2$, so $j\\otimes j=0\\oplus1\\oplus\\dots\\oplus(n-1)$: each hook, one state per $m$, straightens into an $l$-column.',
      apply: () => {
        sN.set(4);
        S.auto = true;
        play.set(true);
      },
    },
    {
      title: 'Sodium: screening by the core',
      text: 'Inside the Na$^+$ core the potential is deeper than $-1/r$, so $\\vec A$ is no longer conserved and $SO(4)$ breaks to $SO(3)$. Penetrating $s$ and $p$ orbits sink; the $n$-shell splits by $l$. Each bar keeps its $2l+1$ dots: rotations are still exact.',
      apply: () => {
        sN.set(3);
        sScr.set(1);
      },
    },
    {
      title: 'The sodium D line',
      text: 'At full screening $E_{3p}-E_{3s}\\approx2.0$ eV (measured 2.10 eV, the 589 nm street-light yellow): the energy cost of breaking the hidden symmetry.',
      apply: () => {
        sN.set(3);
        sScr.set(1);
        seg.set(1);
      },
    },
    {
      title: 'Circular orbits stay hydrogenic',
      text: 'Raise $n$ at full screening: high-$l$ levels hardly move ($\\delta_d,\\delta_f\\approx0$). Large-$L$ orbits never come near the core — classically their perihelion $L^2/k(1+e)$ is large.',
      apply: () => {
        sN.set(5);
        sScr.set(1);
      },
    },
  ]);

  // ------------------------------------------------------------ notes
  pg.note(`<h2>What you see</h2>
    <p>Left: the bound levels of a one-electron atom in columns $l=0,1,2,\\dots$ ($s,p,d,\\dots$), each bar carrying $2l+1$ dots for
    $m=-l,\\dots,l$. The vertical axis is the effective quantum number $n^*$ (so $E=-1/2n^{*2}$ Hartree, energies on the right); for hydrogen
    $n^*=n$ and every shell is one flat row of $n^2$ states.</p>
    <p>Right: the same shell as a multiplet of $SO(4)\\cong SU(2)\\times SU(2)/\\Z_2$. The $n^2$ states form the grid $|m_1,m_2\\rangle$ of
    the representation $(j,j)$, $j=\\tfrac{n-1}{2}$. Regrouping by $m=m_1+m_2$ into nested hooks gives the $l$-multiplets.</p>
    <div class="callout warning"><span class="callout-title">Counting, not wavefunctions</span>The hooks get the weights right — one
    state of each $m$ with $|m|\\le l$ — but the actual $|l\\,m\\rangle$ are Clebsch–Gordan combinations along each diagonal $m_1+m_2=m$.</div>`);
  pg.note(`<h2>The physics: Pauli 1926</h2>
    <p>Pauli solved hydrogen before Schrödinger, with the algebra alone. Quantum mechanically
    $\\vec A=\\tfrac12(\\vec p\\times\\vec L-\\vec L\\times\\vec p)-mk\\,\\hat r$ commutes with $H$; on a level of energy $E<0$ set
    $\\vec A\\,'=\\vec A/\\sqrt{-2mE}$ and $\\vec J_{1,2}=\\tfrac12(\\vec L\\pm\\vec A\\,')$. These are two commuting angular momenta with
    $$\\vec J_1^{\\,2}=\\vec J_2^{\\,2}=j(j+1),\\qquad H=-\\frac{mk^2}{2\\hbar^2\\,(4j(j+1)+1)}=-\\frac{mk^2}{2\\hbar^2 n^2},\\quad n=2j+1 .$$
    The degeneracy $(2j+1)^2=n^2$ is the dimension of an irreducible representation — no accident at all.</p>
    <div class="callout physics"><span class="callout-title">Why the grid is physical</span>The states $|m_1,m_2\\rangle$ diagonalise
    $L_z=J_{1z}+J_{2z}$ and $A'_z=J_{1z}-J_{2z}$: they are the <em>parabolic</em> states. A weak field couples to $\\vec A$ (previous tabs),
    so the linear Stark effect is diagonal in this basis: $E^{(1)}=\\tfrac32\\,n\\,q\\,e a_0F$ with $q=m_1-m_2$ up to a convention-dependent sign.</div>`);
  pg.note(`<h2>The mathematics: branching $SO(4)\\to SO(3)$</h2>
    <p>Irreducible representations of $\\so(4)=\\su(2)\\oplus\\su(2)$ are labelled $(j_1,j_2)$; hydrogen realises only $j_1=j_2$ because
    $\\vec L\\cdot\\vec A=0$ forces $\\vec J_1^{\\,2}=\\vec J_2^{\\,2}$. Restricting to the diagonal $SU(2)$ of ordinary rotations is the addition of
    angular momenta,
    $$(j,j)\\big|_{SO(3)}=j\\otimes j=\\bigoplus_{l=0}^{2j} l=0\\oplus1\\oplus\\dots\\oplus(n-1),\\qquad \\sum_{l=0}^{n-1}(2l+1)=n^2 .$$
    Fock’s $S^3$ explains the same count: the $\\R^4$ harmonic polynomials of degree $n-1$ span exactly $n^2$ dimensions.</p>`);
  pg.note(`<h2>Going further</h2>
    <ul>
      <li><strong>Alkali atoms.</strong> Quantum defects $\\delta_l$ measure how much each $l$ penetrates the core; they are nearly
      $n$-independent, the basis of Rydberg-atom spectroscopy.</li>
      <li><strong>Relativity.</strong> The Dirac equation splits levels by $j=l\\pm\\tfrac12$ (fine structure) but keeps $2s_{1/2}$ and
      $2p_{1/2}$ degenerate — a remnant of the hidden symmetry (Johnson–Lippmann operator). Only QED’s Lamb shift lifts it.</li>
      <li>Including transitions between shells, hydrogen’s spectrum is one irreducible representation of the non-compact $SO(4,2)$.</li>
      <li>Multiplets and Clebsch–Gordan coefficients: <a href="#/reps">spin multiplets</a>; rotations: <a href="#/so3">SO(3)</a>.</li>
    </ul>`);

  // ------------------------------------------------------------ logic
  function bars() {
    const out = [];
    const s = S.screen;
    for (let n = 1; n <= NMAX_LEVELS; n++) {
      for (let l = 0; l < Math.min(n, NCOL); l++) {
        const core = n <= 2;
        const y = core ? n : K.nEff(n, l, s);
        let alpha = core ? 1 - s : 1;
        if (y > NTOP) alpha *= Math.max(0, 1 - (y - NTOP) / 0.35);
        if (n > NCOL && s === 0) alpha = 0;
        if (alpha <= 0.01) continue;
        out.push({ n, l, y, alpha, core });
      }
    }
    return out;
  }

  function update() {
    const n = S.n;
    const j = (n - 1) / 2;
    kv.set('Hydrogen $E_n=-1/2n^2$', `${fmt(-1 / (2 * n * n), 4)} Ha = ${fmt(eVof(n), 2)} eV`);
    kv.set('$j=(n-1)/2$', Number.isInteger(j) ? String(j) : `${2 * j}/2`);
    kv.set('Degeneracy $(2j+1)^2$', `${n * n} = n²`);
    const ls = Array.from({ length: n }, (_, l) => l).join('\\oplus ');
    const jt = Number.isInteger(j) ? String(j) : `\\tfrac{${2 * j}}{2}`;
    ro.set(`(${jt},${jt})\\;\\to\\;${ls}`);
    if (S.screen > 0 && n >= 3) {
      const parts = [];
      for (let l = 0; l < Math.min(n, 4); l++) parts.push(`${n}${K.SPECTRO[l]}:\\,${fmt(K.levelEnergy(n, l, S.screen) * K.HARTREE_EV, 2).replace('−', '-')}`);
      roNa.set(parts.join(',\\ \\ '));
    } else if (S.screen > 0) roNa.set(`n=${n}:\\ \\text{filled core of Na}^+`);
    else roNa.set(`\\text{all } l:\\ ${fmt(eVof(n), 2).replace('−', '-')}\\ \\text{(no splitting)}`);
    caption.innerHTML = ui.h('div', {
      html: S.target === 0 && S.u < 0.5 ? `$(j,j)=(${jt},${jt})$: $\\;n^2=${n * n}$ states $|m_1,m_2\\rangle$` : `$${ls}$: $\\;\\sum(2l+1)=${n * n}$`,
    }).innerHTML;
    const ext = Math.max(j, (n - 1) * SY) + 0.75;
    pG.setView({ x: [-ext - 0.15, ext + 0.15], y: [-ext - 0.35, ext + 0.15] });
    pL.invalidate();
    pG.invalidate();
  }

  let hold = 0;
  scope.frame((dt) => {
    if (S.auto) {
      if (Math.abs(S.u - S.target) < 1e-6) {
        hold += dt;
        if (hold > 1.6) {
          S.target = 1 - S.target;
          seg.set(S.target, { silent: true });
          hold = 0;
        }
      }
    }
    const goal = S.target;
    if (S.u !== goal) {
      const step = dt / 1.5;
      S.u = goal > S.u ? Math.min(goal, S.u + step) : Math.max(goal, S.u - step);
      pG.invalidate();
      if (Math.abs(S.u - 0.5) < step + 1e-9 || S.u === goal) update();
    }
  });

  // ------------------------------------------------------------ drawing
  function drawLevels(p) {
    const ctx = p.ctx;
    const s = S.screen;
    // horizontal guides at integer n*, with n on the left and E = −1/2n*² (eV) on the right
    const xr = p.sx(NCOL - 0.45) + 8;
    for (let n = 1; n <= 5; n++) {
      const Y = Math.round(p.sy(n)) + 0.5;
      ctx.strokeStyle = col.grid;
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.moveTo(p.sx(-0.55), Y);
      ctx.lineTo(p.sx(NCOL - 0.45), Y);
      ctx.stroke();
      ctx.font = '12px system-ui, "Segoe UI", sans-serif';
      ctx.fillStyle = col.ink2;
      ctx.textAlign = 'right';
      ctx.textBaseline = 'middle';
      ctx.fillText(String(n), p.sx(-0.6), Y);
      ctx.textAlign = 'left';
      ctx.font = '11.5px system-ui, "Segoe UI", sans-serif';
      ctx.fillStyle = col.muted;
      ctx.fillText(`${fmt(eVof(n), 2)} eV`, xr, Y - (s < 0.98 ? 7 : 0));
      if (s < 0.98) {
        ctx.globalAlpha = 1 - s;
        ctx.fillStyle = col.ink2;
        ctx.fillText(`${n * n} state${n > 1 ? "s" : ""}`, xr, Y + 8);
        ctx.globalAlpha = 1;
      }
    }
    p.tex(s > 0 ? 'n^*' : 'n', [-0.6, NTOP + 0.3], { key: 'yax', align: 'right', small: true, color: 'muted' });
    // column heads
    for (let l = 0; l < NCOL; l++) p.tex(`${K.SPECTRO[l]}`, [l, NTOP + 0.3], { key: 'h' + l, color: LCOL[l] });
    // bars
    const colW = p.sx(1) - p.sx(0);
    const half = 0.4;
    for (const b of bars()) {
      const sel = b.n === S.n;
      const x0 = b.l - half;
      const x1 = b.l + half;
      const c = LCOL[b.l];
      p.segment([x0, b.y], [x1, b.y], { color: sel ? 'hi' : c, width: sel ? 3 : 1.8, alpha: b.alpha * (sel ? 1 : 0.75) });
      const m = 2 * b.l + 1;
      const r = Math.max(1.6, Math.min(3.4, (colW * 2 * half) / (m * 2.6)));
      for (let q = 0; q < m; q++) {
        const x = b.l + (m === 1 ? 0 : -half * 0.82 + (1.64 * half * q) / (m - 1));
        p.dot([x, b.y], { r, fill: c, alpha: b.alpha });
      }
      if (sel && s > 0.02 && !b.core) p.tex(`\\text{${b.n}${K.SPECTRO[b.l]}}`, [b.l, b.y], { key: `sel${b.l}`, offset: [0, -11], small: true, color: 'hi' });
    }
    if (s > 0.5) p.tex('\\text{Na}^+\\text{ core: }1s^2\\,2s^2\\,2p^6', [1.5, 1.5], { key: 'core', small: true, color: 'muted' });
  }

  function drawGrid(p) {
    const n = S.n;
    const j = (n - 1) / 2;
    const u = easeInOut(S.u);
    const states = K.so4Multiplet(n);
    const pos = (st) => {
      const g = [st.m1, st.m2];
      const lm = [st.l - j, st.m * SY];
      return [g[0] + (lm[0] - g[0]) * u, g[1] + (lm[1] - g[1]) * u];
    };
    // guides: anti-diagonals m1 + m2 = m (grid) fading into rows of constant m
    for (let m = -(n - 1); m <= n - 1; m++) {
      const lo = Math.max(-j, m - j);
      const hi = Math.min(j, m + j);
      const A = [lo, m - lo];
      const B = [hi, m - hi];
      const A2 = [Math.abs(m) - j - 0.35, m * SY];
      const B2 = [j + 0.35, m * SY];
      const P = [A[0] + (A2[0] - A[0]) * u, A[1] + (A2[1] - A[1]) * u];
      const Q = [B[0] + (B2[0] - B[0]) * u, B[1] + (B2[1] - B[1]) * u];
      p.segment(P, Q, { color: 'grid', width: 1, alpha: 0.9 });
    }
    // multiplet polylines (hooks → columns)
    for (let l = 0; l < n; l++) {
      const pts = states.filter((s) => s.l === l).sort((x, y) => x.m - y.m).map(pos);
      if (pts.length > 1) p.line(pts, { color: LCOL[l], width: 2.2, alpha: 0.55 });
    }
    const r = Math.max(4, Math.min(8.5, p.scale * 0.2));
    for (const st of states) p.dot(pos(st), { r, fill: LCOL[st.l], stroke: 'surface', width: 1.5 });
    // axis captions
    const ext = j + 0.6;
    const ga = 1 - u;
    if (ga > 0.05) {
      p.tex('m_1', [ext, -j - 0.55], { key: 'ax1', small: true, color: 'muted' });
      p.tex('m_2', [-j - 0.6, ext - 0.2], { key: 'ax2', small: true, color: 'muted' });
    }
    if (u > 0.05) {
      for (let l = 0; l < n; l++) p.tex(`l=${l}`, [l - j, -(n - 1) * SY - 0.55], { key: 'lx' + l, small: true, color: LCOL[l] });
    }
  }

  // ------------------------------------------------------------ init
  play.set(S.auto, { silent: true });
  seg.set(S.target, { silent: true });
  update();
}
